"""Writes kernel.ptx for probes/lea_hi_not: thread g (8 CTAs x 256) loads a = ar[g][0],
c = ar[g][1], r = ar[g][2] (u32) and x = x[g] (u64) and stores, for s = 1..30,
  out[s - 1][g]  = (zext(a) << s) - x                    (64-bit),
  out[s + 29][g] = ((zext(c) << s) | zext(r)) - (x << s)  (64-bit).
ptxas computes each high word with SASS `LEA.HI.X Rd, Ra, ~Rb, RZ, s, P`: the high word of
the zero-extended word shifted left by s, plus the complemented high word of the subtrahend,
plus the low word's carry P, which comes from `LEA Rlo, P, Ra, -Rxlo, s` in the first shape and
from `LEA Rlo, P, -Rxlo, Rb, s` in the second. (The two shapes read different words so that
ptxas does not share the shifted value between them.)"""

N = 2048
L = []
e = L.append
e("""// Generated by gen_ptx.py (see there for the output layout).
.version 8.8
.target sm_103a
.address_size 64

.visible .entry lea_hi_not(
    .param .u64 par, .param .u64 px, .param .u64 pout
)
.maxntid 256, 1, 1
{
    .reg .b32 %r<8>;
    .reg .b64 %rd<210>;
    mov.u32 %r1, %tid.x;
    mov.u32 %r2, %ctaid.x;
    mad.lo.u32 %r3, %r2, 256, %r1;
    ld.param.u64 %rd1, [par];
    ld.param.u64 %rd2, [px];
    ld.param.u64 %rd3, [pout];
    cvta.to.global.u64 %rd1, %rd1;
    cvta.to.global.u64 %rd2, %rd2;
    cvta.to.global.u64 %rd3, %rd3;
    mul.wide.u32 %rd4, %r3, 8;
    mul.wide.u32 %rd8, %r3, 16;
    add.s64 %rd1, %rd1, %rd8;
    add.s64 %rd2, %rd2, %rd4;
    add.s64 %rd3, %rd3, %rd4;
    ld.global.u32 %r4, [%rd1];
    ld.global.u32 %r5, [%rd1+4];
    ld.global.u32 %r6, [%rd1+8];
    ld.global.u64 %rd5, [%rd2];
    cvt.u64.u32 %rd6, %r4;
    cvt.u64.u32 %rd7, %r5;
    cvt.u64.u32 %rd9, %r6;""")
for s in range(1, 31):
    e(f"    shl.b64 %rd{10 + s}, %rd6, {s};")
    e(f"    sub.s64 %rd{50 + s}, %rd{10 + s}, %rd5;")
    e(f"    st.global.u64 [%rd3+{(s - 1) * N * 8}], %rd{50 + s};")
for s in range(1, 31):
    e(f"    shl.b64 %rd{170 + s}, %rd7, {s};")
    e(f"    or.b64 %rd{90 + s}, %rd{170 + s}, %rd9;")
    e(f"    shl.b64 %rd{130 + s}, %rd5, {s};")
    e(f"    sub.s64 %rd{90 + s}, %rd{90 + s}, %rd{130 + s};")
    e(f"    st.global.u64 [%rd3+{(s + 29) * N * 8}], %rd{90 + s};")
e("    ret;\n}")
open("kernel.ptx", "w").write("\n".join(L) + "\n")
