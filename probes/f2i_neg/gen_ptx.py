"""Writes kernel.ptx for probes/f2i_neg: thread g (8 CTAs x 256) loads x = in[g] (f32),
negates it (neg.f32) and stores, for j = 0..15 (rounding r = j % 4 in rni, rzi, rmi, rpi;
j / 4 = s32, u32, s32.ftz, u32.ftz): out[j][g] = cvt.<r>[.ftz].<s32|u32>.f32 (-x). ptxas folds
the negation into the conversion's source operand: SASS F2I[.FTZ][.U32][.TRUNC|.FLOOR|.CEIL]
.NTZ Rd, -Ra."""

N = 2048
R = ["rni", "rzi", "rmi", "rpi"]
L = []
e = L.append
e("""// Generated by gen_ptx.py (see there for the output layout).
.version 8.8
.target sm_103a
.address_size 64

.visible .entry f2i_neg(
    .param .u64 pin, .param .u64 pout
)
.maxntid 256, 1, 1
{
    .reg .b32 %r<40>;
    .reg .b64 %rd<8>;
    .reg .f32 %f<4>;
    mov.u32 %r1, %tid.x;
    mov.u32 %r2, %ctaid.x;
    mad.lo.u32 %r3, %r2, 256, %r1;
    ld.param.u64 %rd1, [pin];
    ld.param.u64 %rd2, [pout];
    cvta.to.global.u64 %rd1, %rd1;
    cvta.to.global.u64 %rd2, %rd2;
    mul.wide.u32 %rd3, %r3, 4;
    add.s64 %rd1, %rd1, %rd3;
    add.s64 %rd2, %rd2, %rd3;
    ld.global.f32 %f1, [%rd1];
    neg.f32 %f2, %f1;""")
for j in range(16):
    t = "s32" if j // 4 % 2 == 0 else "u32"
    ftz = ".ftz" if j >= 8 else ""
    e(f"    cvt.{R[j % 4]}{ftz}.{t}.f32 %r{j + 10}, %f2;")
    e(f"    st.global.u32 [%rd2+{j * N * 4}], %r{j + 10};")
e("    ret;\n}")
open("kernel.ptx", "w").write("\n".join(L) + "\n")
