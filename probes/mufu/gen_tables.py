"""Emit crates/sim/src/mufu_tables.rs from the per-function fits in fits/*.json (see README.md).
python gen_tables.py > ../../crates/sim/src/mufu_tables.rs"""

import json
import os

D = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fits")


def load(n):
    return json.load(open(os.path.join(D, n)))


out = []


def emit(name, doc, n, col, a, r, b, c, sh, tab):
    out.append(f"/// {doc}")
    out.append(f"pub(crate) const {name}: Interp = Interp {{")
    out.append(
        f"    n: {n},\n    col: {col},\n    a: {a},\n    r: {r},\n    b: {b},\n    c: {c},\n    sh: {sh},"
    )
    out.append("    tab: &[")
    for t in tab:
        out.append(f"        ({t[0]}, {t[1]}, {t[2]}),")
    out.append("    ],\n};\n")


e = load("fit_ex2.json")
emit(
    "EX2",
    "MUFU.EX2: 2^(f / 2^23), f in [0, 2^23); result mantissa (hidden bit included), units 2^-23.",
    17,
    19,
    32,
    e["rlo"],
    19,
    0,
    34,
    [(q, c1q, c2) for _, q, c1q, c2 in e["tab"]],
)
f = load("fit_rcp.json")
assert all(c1 % 2 == 0 for _, c1, _ in f["tab"])
emit(
    "RCP",
    "MUFU.RCP: 1 / (1 + f / 2^23); result in (2^23, 2^24], units 2^-24.",
    16,
    17,
    32,
    f["r"],
    19,
    2,
    34,
    [(q, c1 // 2, c2) for q, c1, c2 in f["tab"]],
)
f = load("fit_rsq.json")
assert all(c1 % 2 == 0 for _, c1, _ in f["tab"])
emit(
    "RSQ",
    "MUFU.RSQ: 1 / sqrt(x), x = (1 + f / 2^23) * 2^p, index p << 23 | f; result units 2^-24.",
    17,
    19,
    32,
    f["r"],
    18,
    0,
    34,
    [(q, c1 // 2, c2) for q, c1, c2 in f["tab"]],
)
f = load("fit_sqrt.json")
emit(
    "SQRT",
    "MUFU.SQRT: sqrt(x), x = (1 + f / 2^23) * 2^p, index p << 23 | f; result units 2^-23.",
    17,
    19,
    34,
    f["r"],
    19,
    1,
    36,
    f["tab"],
)
f = load("fit_lg2.json")
emit(
    "LG2",
    "MUFU.LG2: log2(1 + f / 2^23) as a fixed-point fraction, units 2^-36.",
    17,
    19,
    22,
    f["r"],
    10,
    -12,
    12,
    f["tab"],
)
f = load("fit_sin.json")
emit(
    "SIN",
    "MUFU.SIN/COS: sin(pi/2 * u / 2^23), u in [0, 2^23), fixed point, units 2^-37.",
    17,
    19,
    24,
    f["r"],
    11,
    -7,
    12,
    f["tab"],
)
print(
    "/*\n"
    " * Copyright (c) Meta Platforms, Inc. and affiliates.\n"
    " *\n"
    " * This source code is licensed under the BSD-style license found in the\n"
    " * LICENSE file in the root directory of this source tree.\n"
    " */\n"
)
print(
    "//! Generated by probes/mufu/gen_tables.py from the GB300 sweep fits; do not edit.\n"
)
print("use crate::mufu::Interp;\n")
print("\n".join(out))
t = load("fit_tanh.json")
K = {int(e): k for e, k in t["K"].items()}
print(
    "/// MUFU.TANH mantissa width K per binade e = -8..=2 (index e + 8): see `mufu::tanh`."
)
print(f"pub(crate) const TANH_K: [u32; 11] = {[K[e] for e in range(-8, 3)]};\n")
print(
    "/// MUFU.TANH segment tables per binade (index e + 8): (C0, C1, C2), S in units 2^(e-66)."
)
print("pub(crate) const TANH: [&[(i128, i64, i64)]; 11] = [")
for e in range(-8, 3):
    rows = sorted((s, c0, c1, c2) for ee, s, c0, c1, c2 in t["tab"] if ee == e)
    assert [r[0] for r in rows] == list(range(1 << (K[e] - 17)))
    print("    &[")
    for _, c0, c1, c2 in rows:
        print(f"        ({c0}, {c1}, {c2}),")
    print("    ],")
print("];")
