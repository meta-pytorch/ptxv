"""Writes kernel.ptx: the low-precision cvt probe (N-CVT-LP). Thread i reads x, y, z, w, r
(u32 words) and writes one word per op to out[i * NOPS + j]. OPS order is the contract with
crates/sim/src/lowp.rs (`CVT_PROBE_OPS`)."""

import sys

F8 = ["e4m3", "e5m2", "e2m3", "e3m2", "e2m1"]
OPS = []  # (name, ptx lines producing %o (b32))
for t in F8:
    for relu in ["", ".relu"]:
        dst = "%c1" if t == "e2m1" else "%h2"
        widen = "cvt.u32.u8 %o, %c1;" if t == "e2m1" else "cvt.u32.u16 %o, %h2;"
        OPS.append(
            (
                f"rn.satfinite{relu}.{t}x2.f32",
                f"cvt.rn.satfinite{relu}.{t}x2.f32 {dst}, %fx, %fy; {widen}",
            )
        )
for rnd in ["rz", "rp"]:
    for sat in [".satfinite", ""]:
        OPS.append(
            (
                f"{rnd}{sat}.ue8m0x2.f32",
                f"cvt.{rnd}{sat}.ue8m0x2.f32 %h2, %fx, %fy; cvt.u32.u16 %o, %h2;",
            )
        )
for t in ["e4m3", "e5m2"]:
    for relu in ["", ".relu"]:
        OPS.append(
            (
                f"rn.satfinite{relu}.{t}x2.f16x2",
                f"cvt.rn.satfinite{relu}.{t}x2.f16x2 %h2, %x; cvt.u32.u16 %o, %h2;",
            )
        )
for rnd in ["rz", "rp"]:
    for sat in [".satfinite", ""]:
        OPS.append(
            (
                f"{rnd}{sat}.ue8m0x2.bf16x2",
                f"cvt.{rnd}{sat}.ue8m0x2.bf16x2 %h2, %x; cvt.u32.u16 %o, %h2;",
            )
        )
for t in ["e4m3", "e5m2", "e2m3", "e3m2"]:
    for relu in ["", ".relu"]:
        OPS.append((f"rn{relu}.f16x2.{t}x2", f"cvt.rn{relu}.f16x2.{t}x2 %o, %xh;"))
OPS.append(("rn.bf16x2.ue8m0x2", "cvt.rn.bf16x2.ue8m0x2 %o, %xh;"))
for relu in ["", ".relu"]:
    OPS.append((f"rn{relu}.f16x2.e2m1x2", f"cvt.rn{relu}.f16x2.e2m1x2 %o, %xc;"))
for t in F8:
    for relu in ["", ".relu"]:
        if t == "e2m1":
            OPS.append(
                (
                    f"rs.satfinite{relu}.{t}x4.f32",
                    f"cvt.rs.satfinite{relu}.{t}x4.f32 %h2, {{%fx, %fy, %fz, %fw}}, %r; cvt.u32.u16 %o, %h2;",
                )
            )
        else:
            OPS.append(
                (
                    f"rs.satfinite{relu}.{t}x4.f32",
                    f"cvt.rs.satfinite{relu}.{t}x4.f32 %o, {{%fx, %fy, %fz, %fw}}, %r;",
                )
            )
for t in ["f16x2", "bf16x2"]:
    for mods in ["", ".relu", ".satfinite", ".relu.satfinite"]:
        OPS.append((f"rs{mods}.{t}.f32", f"cvt.rs{mods}.{t}.f32 %o, %fx, %fy, %r;"))


def ptx():
    body = []
    for j, (name, code) in enumerate(OPS):
        body.append(f"    // {j}: {name}")
        body.append("    " + code.replace("%o", "%o"))
        body.append(f"    st.global.u32 [%rd6+{4 * j}], %o;")
    return f"""// N-CVT-LP probe (generated by gen.py; do not edit): {len(OPS)} low-precision cvt forms.
// Thread i: x, y, z, w = f32 operands (x also as f16x2 / bf16x2, its low 16 / 8 bits as the
// packed 8-bit / 4-bit source), r = random bits for .rs; out[i * {len(OPS)} + j] = op j.
.version 9.0
.target sm_103a
.address_size 64

.visible .entry cvt_lp(.param .u64 x_p, .param .u64 y_p, .param .u64 z_p, .param .u64 w_p,
    .param .u64 r_p, .param .u64 out_p)
{{
    .reg .b32 %x, %y, %z, %w, %r, %o, %t<4>;
    .reg .f32 %fx, %fy, %fz, %fw;
    .reg .b16 %xh, %h2;
    .reg .b8 %xc, %c1;
    .reg .b64 %rd<12>;
    mov.u32 %t0, %ctaid.x;
    mov.u32 %t1, %ntid.x;
    mov.u32 %t2, %tid.x;
    mad.lo.u32 %t3, %t0, %t1, %t2;
    mul.wide.u32 %rd1, %t3, 4;
    ld.param.u64 %rd2, [x_p];
    add.u64 %rd3, %rd2, %rd1;
    ld.global.u32 %x, [%rd3];
    ld.param.u64 %rd2, [y_p];
    add.u64 %rd3, %rd2, %rd1;
    ld.global.u32 %y, [%rd3];
    ld.param.u64 %rd2, [z_p];
    add.u64 %rd3, %rd2, %rd1;
    ld.global.u32 %z, [%rd3];
    ld.param.u64 %rd2, [w_p];
    add.u64 %rd3, %rd2, %rd1;
    ld.global.u32 %w, [%rd3];
    ld.param.u64 %rd2, [r_p];
    add.u64 %rd3, %rd2, %rd1;
    ld.global.u32 %r, [%rd3];
    mov.b32 %fx, %x;
    mov.b32 %fy, %y;
    mov.b32 %fz, %z;
    mov.b32 %fw, %w;
    cvt.u16.u32 %xh, %x;
    cvt.u8.u32 %xc, %x;
    mul.wide.u32 %rd4, %t3, {4 * len(OPS)};
    ld.param.u64 %rd5, [out_p];
    add.u64 %rd6, %rd5, %rd4;
{chr(10).join(body)}
    ret;
}}
"""


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "--names":
        for j, (n, _) in enumerate(OPS):
            print(j, n)
    else:
        open("kernel.ptx", "w").write(ptx())
        print(len(OPS), "ops")
