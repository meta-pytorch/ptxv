"""Writes probes/bf16_ext/kernel.ptx."""

OPS = [
    ("fma.rn.f32.bf16 %r{d}, %h1, %h3, %r6;", "FHFMA.BF16: a.lo * b.lo + c"),
    ("fma.rz.f32.bf16 %r{d}, %h2, %h4, %r6;", "FHFMA.BF16.RZ: a.hi * b.hi + c"),
    ("fma.rm.f32.bf16 %r{d}, %h1, %h4, %r7;", "FHFMA.BF16.RM: a.lo * b.hi + e"),
    ("fma.rp.f32.bf16 %r{d}, %h2, %h3, %r7;", "FHFMA.BF16.RP: a.hi * b.lo + e"),
    ("fma.rn.sat.f32.bf16 %r{d}, %h1, %h3, %r7;", "FHFMA.BF16.SAT: a.lo * b.lo + e"),
    ("add.rn.f32.bf16 %r{d}, %h1, %r6;", "FHADD.BF16: a.lo + c"),
    ("sub.rz.f32.bf16 %r{d}, %h2, %r7;", "FHADD.BF16.RZ: a.hi - e"),
    ("add.rp.f32.bf16 %r{d}, %h4, %r6;", "FHADD.BF16.RP: b.hi + c"),
    ("add.rm.f32.bf16 %r{d}, %h3, %r7;", "FHADD.BF16.RM: b.lo + e"),
    ("min.bf16x2 %r{d}, %r4, %r5;", "HMNMX2.BF16_V2 a, b, PT"),
    ("max.bf16x2 %r{d}, %r4, %r5;", "HMNMX2.BF16_V2 a, b, !PT"),
    ("min.NaN.bf16x2 %r{d}, %r4, %r5;", "HMNMX2.BF16_V2.NAN"),
    ("max.xorsign.abs.bf16x2 %r{d}, %r4, %r5;", "HMNMX2.BF16_V2.XORSIGN"),
    ("min.NaN.xorsign.abs.bf16x2 %r{d}, %r4, %r5;", "HMNMX2.BF16_V2.NAN.XORSIGN"),
    (
        "min.bf16 %h10, %h1, %h4; max.NaN.bf16 %h11, %h2, %h3; mov.b32 %r{d}, {{%h10, %h11}};",
        "lanes min.bf16 a.lo, b.hi / max.NaN.bf16 a.hi, b.lo (.H0_H0 / .H1_H1)",
    ),
]
F2 = [
    ("fma.rz.f32x2", 3),
    ("fma.rm.f32x2", 3),
    ("fma.rp.f32x2", 3),
    ("mul.rm.f32x2", 2),
    ("add.rz.f32x2", 2),
    ("mul.rp.f32x2", 2),
    ("add.rm.f32x2", 2),
    ("sub.rp.f32x2", 2),
]
hdr = [
    "// probes/bf16_ext (generated by gen_ptx.py): mixed bf16 / f32 FMA and add, bf16 min / max,",
    "// and f32x2 in the directed rounding modes, against GB300. Thread g (16 CTAs x 256) loads",
    "// (a, b, c, e) = in[g] (gen.py; a, b packed bf16x2, c, e f32) and stores out[j][g]:",
]
lines = []
j = 0
for s, desc in OPS:
    hdr.append(f"//   j = {j}: {s.split(' %')[0]} ({desc})")
    lines.append("    " + s.format(d=20 + j))
    j += 1
for name, n in F2:
    srcs = "%rd6, %rd7, %rd8" if n == 3 else "%rd6, %rd7"
    ab = "{c, e}, {a, b}" + (", {e, c}" if n == 3 else "")
    hdr.append(
        f"//   j = {j}, {j + 1}: lanes of {name} {ab} (FFMA2 / FMUL2 / FADD2 with a rounding mode)"
    )
    lines.append(f"    {name} %rd9, {srcs};")
    lines.append(f"    mov.b64 {{%r{20 + j}, %r{21 + j}}}, %rd9;")
    j += 2
K = j
body = "\n".join(lines)
stores = "\n".join(
    f"    st.global.u32   [%rd5+{16384 * k}], %r{20 + k};" for k in range(K)
)
ptx = (
    "\n".join(hdr)
    + f"""
.version 8.8
.target sm_103a
.address_size 64

.visible .entry bf16_ext(
    .param .u64 pin,
    .param .u64 pout
)
.maxntid 256, 1, 1
{{
    .reg .b32   %r<64>;
    .reg .b16   %h<16>;
    .reg .b64   %rd<12>;

    ld.param.u64    %rd1, [pin];
    ld.param.u64    %rd2, [pout];
    cvta.to.global.u64 %rd1, %rd1;
    cvta.to.global.u64 %rd2, %rd2;
    mov.u32         %r1, %tid.x;
    mov.u32         %r2, %ctaid.x;
    mad.lo.u32      %r3, %r2, 256, %r1;
    mul.wide.u32    %rd3, %r3, 16;
    add.s64         %rd3, %rd1, %rd3;
    ld.global.v4.u32 {{%r4, %r5, %r6, %r7}}, [%rd3];
    mul.wide.u32    %rd4, %r3, 4;
    add.s64         %rd5, %rd2, %rd4;
    mov.b32         {{%h1, %h2}}, %r4;
    mov.b32         {{%h3, %h4}}, %r5;
    mov.b64         %rd6, {{%r6, %r7}};
    mov.b64         %rd7, {{%r4, %r5}};
    mov.b64         %rd8, {{%r7, %r6}};
{body}
{stores}
    ret;
}}
"""
)
open("kernel.ptx", "w").write(ptx)
