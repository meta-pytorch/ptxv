"""Writes kernel.ptx: the block-scaled tcgen05.mma probe (N-MMA-BS), one entry per kind:
mma_mxf8 (kind::mxf8f6f4, scale_vec::1X), mma_mxf4 (kind::mxf4, 2X), mma_nvf4 (kind::mxf4nvf4,
4X), mma_nvf4_2x (kind::mxf4nvf4, 2X). Derived from probes/mma_f8: the same operand tiles, plus
scale factors that every thread writes to TMEM with tcgen05.st (SFA[lane][j] -> column 64 + j,
SFB[lane][j] -> column 96 + j, j < 16); MMA k (of 4) reads SFA at column 64 + 4k, SFB at
96 + 4k."""

src = open("../mma_f8/kernel.ptx").read()
KINDS = [
    ("mma_mxf8", "kind::mxf8f6f4.block_scale.scale_vec::1X"),
    ("mma_mxf4", "kind::mxf4.block_scale.scale_vec::2X"),
    ("mma_nvf4", "kind::mxf4nvf4.block_scale.scale_vec::4X"),
    ("mma_nvf4_2x", "kind::mxf4nvf4.block_scale.scale_vec::2X"),
]


def entry(name, kind):
    s = src[src.index(".visible .entry") :]
    s = s.replace(".visible .entry mma_f8(", f".visible .entry {name}(")
    s = s.replace(
        "    .param .u32 idesc0\n)",
        "    .param .u32 idesc0,\n    .param .u64 sfa,\n    .param .u64 sfb\n)",
    )
    s = s.replace("[%r2], 64;", "[%r2], 128;").replace("%r5, 64;", "%r5, 128;")
    # Scale factors -> TMEM, after the TMEM address is known; then a second barrier.
    s = s.replace(
        """    ld.shared.b32   %r5, [%r2];                     // TMEM base address (lane 0, column c0)
""",
        """    ld.shared.b32   %r5, [%r2];                     // TMEM base address (lane 0, column c0)
    // Scale factors: thread t writes SFA[t][0..16] to TMEM lane t, columns 64..79, and
    // SFB[t][0..16] to columns 96..111 (each warp its own 32 lanes).
    shl.b32         %r41, %r1, 21;                  // (32 * warp) << 16
    add.u32         %r42, %r5, %r41;
    ld.param.u64    %rd20, [sfa];
    cvta.to.global.u64 %rd20, %rd20;
    mul.wide.u32    %rd21, %r0, 64;
    add.u64         %rd22, %rd20, %rd21;
    ld.global.v4.b32 {%r50, %r51, %r52, %r53}, [%rd22];
    ld.global.v4.b32 {%r54, %r55, %r56, %r57}, [%rd22+16];
    ld.global.v4.b32 {%r58, %r59, %r60, %r61}, [%rd22+32];
    ld.global.v4.b32 {%r62, %r63, %r64, %r65}, [%rd22+48];
    add.u32         %r47, %r42, 64;
    tcgen05.st.sync.aligned.32x32b.x16.b32 [%r47], {%r50, %r51, %r52, %r53, %r54, %r55, %r56, %r57, %r58, %r59, %r60, %r61, %r62, %r63, %r64, %r65};
    ld.param.u64    %rd20, [sfb];
    cvta.to.global.u64 %rd20, %rd20;
    add.u64         %rd22, %rd20, %rd21;
    ld.global.v4.b32 {%r50, %r51, %r52, %r53}, [%rd22];
    ld.global.v4.b32 {%r54, %r55, %r56, %r57}, [%rd22+16];
    ld.global.v4.b32 {%r58, %r59, %r60, %r61}, [%rd22+32];
    ld.global.v4.b32 {%r62, %r63, %r64, %r65}, [%rd22+48];
    add.u32         %r47, %r42, 96;
    tcgen05.st.sync.aligned.32x32b.x16.b32 [%r47], {%r50, %r51, %r52, %r53, %r54, %r55, %r56, %r57, %r58, %r59, %r60, %r61, %r62, %r63, %r64, %r65};
    tcgen05.wait::st.sync.aligned;
    tcgen05.fence::before_thread_sync;
    bar.sync        0;
    tcgen05.fence::after_thread_sync;
""",
    )
    s = s.replace(".reg .b32   %r<48>;", ".reg .b32   %r<72>;")
    s = s.replace(".reg .b64   %rd<24>;", ".reg .b64   %rd<32>;")
    mma = s[
        s.index("    tcgen05.mma.cta_group::1.kind::f8f6f4 [%r5], %rd5") : s.index(
            "    tcgen05.commit"
        )
    ]
    lines = [ln for ln in mma.split("\n") if ln.strip()]
    out = []
    k = 0
    for ln in lines:
        if "tcgen05.mma" in ln:
            out.append(f"    add.u32         %r48, %r5, {64 + 4 * k};")
            out.append(f"    add.u32         %r49, %r5, {96 + 4 * k};")
            ln = ln.replace("kind::f8f6f4", kind)
            ln = ln.replace(", %p3;", ", [%r48], [%r49], %p3;").replace(
                ", %p4;", ", [%r48], [%r49], %p4;"
            )
            k += 1
        out.append(ln)
    s = s.replace(mma, "\n".join(out) + "\n")
    return s


hdr = """// N-MMA-BS probe (generated by gen.py; do not edit). Each entry computes D[128x64] f32 =
// sum over 4 block-scaled tcgen05.mma of A[128xK] * B[64xK]^T, operand bytes as in
// probes/mma_f8 (32 bytes per row and MMA), scale factors written to TMEM with tcgen05.st:
// SFA[t][j] -> lane t, column 64 + j; SFB[t][j] -> lane t, column 96 + j (j < 16); MMA k
// reads [SFA] = column 64 + 4k, [SFB] = column 96 + 4k. idesc / idesc0 are parameters.
.version 9.0
.target sm_103a
.address_size 64

"""
open("kernel.ptx", "w").write(hdr + "\n".join(entry(n, k) for n, k in KINDS))
