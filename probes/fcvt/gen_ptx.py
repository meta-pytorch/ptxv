"""Writes kernel.ptx for probes/fcvt: thread g (32 CTAs x 256) converts in32[g] (f32),
in64[g] (f64) and in16[g] (a 16-bit pattern read as f16 and as bf16) and stores
  out32[j][g], j = 0..7:  cvt.{rni,rzi,rmi,rpi}[.ftz].f32.f32           (SASS FRND[.FTZ][.TRUNC|.FLOOR|.CEIL])
  out64[j][g], j = 0..3:  cvt.{rni,rzi,rmi,rpi}.f64.f64                  (FRND.F64.*)
               j = 4, 5:  cvt.f64.bf16, cvt.f64.f16 of in16             (F2F.F64.BF16 / .F16)
  out16[j][g], j = 0..3:  cvt.{rn,rz,rm,rp}.bf16.f64 of in64            (F2F.BF16.F64[.RZ|.RM|.RP])
               j = 4..7:  cvt.{rn,rz,rm,rp}.f16.f64                     (F2F.F16.F64.*)
               j = 8..11: cvt.{rni,rzi,rmi,rpi}.f16.f16 of in16         (FRND.F16.*)
               j = 12..15: cvt.{rni,rzi,rmi,rpi}.bf16.bf16              (FRND.BF16.*)
               j = 16..19: cvt.{rn,rz,rm,rp}.bf16.f16                   (F2F.BF16.F16.*)
               j = 20..23: cvt.{rn,rz,rm,rp}.f16.bf16                   (F2F.F16.BF16.*)
  out64[6][g], out64[7][g], out16[24][g], out16[25][g]: cvt.f64.f16, cvt.f64.bf16,
               cvt.rn.bf16.f16 and cvt.rn.f16.bf16 of the high half of in32 (the `.H1`
               source selector of F2F.F64.F16 / .F64.BF16 / .BF16.F16 / .F16.BF16)
"""

N = 8192
R = ["rn", "rz", "rm", "rp"]
L = []
e = L.append
e("""// Generated by gen_ptx.py (see there for the output layout).
.version 8.8
.target sm_103a
.address_size 64

.visible .entry fcvt(
    .param .u64 p16, .param .u64 p32, .param .u64 p64,
    .param .u64 o16, .param .u64 o32, .param .u64 o64
)
.maxntid 256, 1, 1
{
    .reg .b32 %r<16>;
    .reg .b64 %rd<64>;
    .reg .f32 %f<16>;
    .reg .f64 %fd<16>;
    .reg .b16 %h<40>;
    mov.u32 %r1, %tid.x;
    mov.u32 %r2, %ctaid.x;
    mad.lo.u32 %r3, %r2, 256, %r1;
    ld.param.u64 %rd1, [p16];
    ld.param.u64 %rd2, [p32];
    ld.param.u64 %rd3, [p64];
    ld.param.u64 %rd4, [o16];
    ld.param.u64 %rd5, [o32];
    ld.param.u64 %rd6, [o64];
    mul.wide.u32 %rd7, %r3, 2;
    mul.wide.u32 %rd8, %r3, 4;
    mul.wide.u32 %rd9, %r3, 8;
    add.s64 %rd1, %rd1, %rd7;
    add.s64 %rd2, %rd2, %rd8;
    add.s64 %rd3, %rd3, %rd9;
    add.s64 %rd4, %rd4, %rd7;
    add.s64 %rd5, %rd5, %rd8;
    add.s64 %rd6, %rd6, %rd9;
    ld.global.b16 %h1, [%rd1];
    ld.global.f32 %f1, [%rd2];
    ld.global.u32 %r4, [%rd2];
    ld.global.f64 %fd1, [%rd3];""")
for j in range(8):
    ftz = ".ftz" if j >= 4 else ""
    e(f"    cvt.{R[j % 4]}i{ftz}.f32.f32 %f{2 + j}, %f1;")
    e(f"    st.global.f32 [%rd5+{j * N * 4}], %f{2 + j};")
for j in range(4):
    e(f"    cvt.{R[j]}i.f64.f64 %fd{2 + j}, %fd1;")
    e(f"    st.global.f64 [%rd6+{j * N * 8}], %fd{2 + j};")
e("    cvt.f64.bf16 %fd6, %h1;")
e(f"    st.global.f64 [%rd6+{4 * N * 8}], %fd6;")
e("    cvt.f64.f16 %fd7, %h1;")
e(f"    st.global.f64 [%rd6+{5 * N * 8}], %fd7;")
ops16 = []
for r in R:
    ops16.append(f"cvt.{r}.bf16.f64 %h{{}}, %fd1;")
for r in R:
    ops16.append(f"cvt.{r}.f16.f64 %h{{}}, %fd1;")
for r in R:
    ops16.append(f"cvt.{r}i.f16.f16 %h{{}}, %h1;")
for r in R:
    ops16.append(f"cvt.{r}i.bf16.bf16 %h{{}}, %h1;")
for r in R:
    ops16.append(f"cvt.{r}.bf16.f16 %h{{}}, %h1;")
for r in R:
    ops16.append(f"cvt.{r}.f16.bf16 %h{{}}, %h1;")
for j, op in enumerate(ops16):
    e("    " + op.format(2 + j))
    e(f"    st.global.b16 [%rd4+{j * N * 2}], %h{2 + j};")
e("    mov.b32 {%h30, %h31}, %r4;")
e("    cvt.f64.f16 %fd8, %h31;")
e(f"    st.global.f64 [%rd6+{6 * N * 8}], %fd8;")
e("    cvt.rn.bf16.f16 %h32, %h31;")
e(f"    st.global.b16 [%rd4+{24 * N * 2}], %h32;")
e("    cvt.f64.bf16 %fd9, %h31;")
e(f"    st.global.f64 [%rd6+{7 * N * 8}], %fd9;")
e("    cvt.rn.f16.bf16 %h33, %h31;")
e(f"    st.global.b16 [%rd4+{25 * N * 2}], %h33;")
e("    ret;\n}")
open("kernel.ptx", "w").write("\n".join(L) + "\n")
