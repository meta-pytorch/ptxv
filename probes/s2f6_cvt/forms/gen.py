"""Writes the s2f6 dequant probe (N-CVT-LP): kernel.ptx, the 1024-thread sample case's inputs
(in_x.bin, in_y.bin), and with --full DIR a 65536-thread case that covers every (code, scale)
pair in each of the four lane positions. kernel.cubin is ptxas 13.1 -arch=sm_103a kernel.ptx
(PTX ISA 9.1: ptxas 13.0 rejects the cvt). Thread i reads x (four s2f6 codes) and y (four ue8m0
scales); op j writes cvt(x.lo16, y.lo16) to out[8 i + 2 j] and cvt(x.hi16, y.hi16) to
out[8 i + 2 j + 1]. `full_inputs` is the contract with crates/sim/tests/lowp.rs, which replays
sweep.json (FNV-1a hashes of each GPU's outputs of the full set, per op) against the model.

Usage: python3 gen.py; python3 gen.py --full DIR; python3 gen.py --record GPU OUT.bin, where
GPU (gb200, gb300) names the GPU whose full-set output OUT.bin is: its hashes go into
sweep.json under that name and its outputs of the sample threads into GPU_out.bin.
"""

import json
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OPS = ["rn.satfinite", "rn", "rn.relu", "rn.relu.satfinite"]


def full_inputs():
    """Thread i (p = i % 256, q = i / 256): lane positions 0..3 of (x, y) get the (code, scale)
    pairs (p, q), (q, p), (p ^ 0x5a, q ^ 0xc3), (q ^ 0x96, p ^ 0x2d): each position sees every
    pair once, and its neighbours vary independently of it."""
    xs, ys = [], []
    for i in range(1 << 16):
        p, q = i & 0xFF, i >> 8
        xs.append((q ^ 0x96) << 24 | (p ^ 0x5A) << 16 | q << 8 | p)
        ys.append((p ^ 0x2D) << 24 | (q ^ 0xC3) << 16 | p << 8 | q)
    return xs, ys


def sample():
    """1024 threads of the full set: every pair of 16 edge codes and 16 edge scales in lane
    position 0, then 768 threads from a fixed LCG."""
    codes = [
        0x00,
        0x01,
        0x02,
        0x3F,
        0x40,
        0x41,
        0x55,
        0x7E,
        0x7F,
        0x80,
        0x81,
        0xBF,
        0xC0,
        0xC1,
        0xFE,
        0xFF,
    ]
    scales = [0, 1, 2, 6, 7, 126, 127, 128, 133, 134, 247, 248, 252, 253, 254, 255]
    idx = [s << 8 | c for s in scales for c in codes]
    seen, r = set(idx), 12345
    while len(idx) < 1024:
        r = (r * 1103515245 + 12345) % (1 << 31)
        i = r >> 15
        if i not in seen:
            seen.add(i)
            idx.append(i)
    return idx


def ptx():
    body = []
    for j, m in enumerate(OPS):
        body.append(f"    // {j}: {m}")
        for h, (a, s) in enumerate([("%xl", "%yl"), ("%xh", "%yh")]):
            body.append(f"    cvt.{m}.scaled::n2::ue8m0.bf16x2.s2f6x2 %o, {a}, {s};")
            body.append(f"    st.global.u32 [%rd6+{8 * j + 4 * h}], %o;")
    return f"""// Copyright (c) Meta Platforms, Inc. and affiliates.
//
// This source code is licensed under the BSD-style license found in the
// LICENSE file in the root directory of this source tree.

// N-CVT-LP s2f6 probe (generated by gen.py; do not edit): the MXINT8 dequant
// cvt.rn[.relu][.satfinite].scaled::n2::ue8m0.bf16x2.s2f6x2 (SASS F2FP[.SATFINITE][.RELU].BF16
// .S2_6.UNPACK_B Rd, Ra[.H1], Rb.H0). Thread i: x = four s2f6 codes, y = four ue8m0 scales;
// op j converts (x.lo16, y.lo16) into out[8 i + 2 j] and (x.hi16, y.hi16) into
// out[8 i + 2 j + 1].
.version 9.1
.target sm_103a
.address_size 64

.visible .entry cvt_s2f6(.param .u64 x_p, .param .u64 y_p, .param .u64 out_p)
{{
    .reg .b32 %x, %y, %o, %t<4>;
    .reg .b16 %xl, %xh, %yl, %yh;
    .reg .b64 %rd<8>;
    mov.u32 %t0, %ctaid.x;
    mov.u32 %t1, %ntid.x;
    mov.u32 %t2, %tid.x;
    mad.lo.u32 %t3, %t0, %t1, %t2;
    mul.wide.u32 %rd1, %t3, 4;
    ld.param.u64 %rd2, [x_p];
    add.u64 %rd3, %rd2, %rd1;
    ld.global.u32 %x, [%rd3];
    ld.param.u64 %rd2, [y_p];
    add.u64 %rd3, %rd2, %rd1;
    ld.global.u32 %y, [%rd3];
    mov.b32 {{%xl, %xh}}, %x;
    mov.b32 {{%yl, %yh}}, %y;
    mul.wide.u32 %rd4, %t3, {8 * len(OPS)};
    ld.param.u64 %rd5, [out_p];
    add.u64 %rd6, %rd5, %rd4;
{chr(10).join(body)}
    ret;
}}
"""


CASE = '''name = "{name}"
description = """
{desc}"""
ptx = "{ptx}"
arch = "sm_103a"
entry = "cvt_s2f6"
grid = [{grid}, 1, 1]
block = [128, 1, 1]
outputs = ["out"]

[[buffers]]
name = "x"
dtype = "u32"
shape = [{n}]
init = "file"
file = "{x}"

[[buffers]]
name = "y"
dtype = "u32"
shape = [{n}]
init = "file"
file = "{y}"

[[buffers]]
name = "out"
dtype = "u32"
shape = [{nout}]
init = "zeros"{expect}

[[params]]
kind = "ptr"
buffer = "x"

[[params]]
kind = "ptr"
buffer = "y"

[[params]]
kind = "ptr"
buffer = "out"

[[variants]]
id = "good"
expect = ["clean"]
'''


def words(path, v):
    open(path, "wb").write(struct.pack(f"<{len(v)}I", *v))


def fnv(ws):
    h = 0xCBF29CE484222325
    for w in ws:
        for b in struct.pack("<I", w):
            h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def main():
    xs, ys = full_inputs()
    n_ops = 2 * len(OPS)
    if len(sys.argv) == 3 and sys.argv[1] == "--full":
        d = sys.argv[2]
        os.makedirs(d, exist_ok=True)
        open(os.path.join(d, "kernel.ptx"), "w").write(ptx())
        words(os.path.join(d, "x.bin"), xs)
        words(os.path.join(d, "y.bin"), ys)
        open(os.path.join(d, "case.toml"), "w").write(
            CASE.format(
                name="cvt_s2f6_full",
                desc="probes/s2f6_cvt/forms --full: every (code, scale) pair in each lane position.",
                ptx="kernel.ptx",
                grid=512,
                n=1 << 16,
                x="x.bin",
                y="y.bin",
                nout=n_ops << 16,
                expect="",
            )
        )
        return
    if len(sys.argv) == 4 and sys.argv[1] == "--record":
        gpu = sys.argv[2]
        raw = open(sys.argv[3], "rb").read()
        out = struct.unpack(f"<{len(raw) // 4}I", raw)
        assert len(out) == n_ops << 16
        path = os.path.join(HERE, "sweep.json")
        rec = json.load(open(path)) if os.path.exists(path) else {}
        for j, m in enumerate(OPS):
            ws = (
                w
                for i in range(1 << 16)
                for w in out[n_ops * i + 2 * j : n_ops * i + 2 * j + 2]
            )
            rec.setdefault(m, {"threads": 1 << 16})[gpu] = f"{fnv(ws):016x}"
        open(path, "w").write(json.dumps(rec, indent=2, sort_keys=True) + "\n")
        idx = sample()
        words(
            os.path.join(HERE, f"{gpu}_out.bin"),
            [w for i in idx for w in out[n_ops * i : n_ops * (i + 1)]],
        )
        return
    open(os.path.join(HERE, "kernel.ptx"), "w").write(ptx())
    idx = sample()
    words(os.path.join(HERE, "in_x.bin"), [xs[i] for i in idx])
    words(os.path.join(HERE, "in_y.bin"), [ys[i] for i in idx])
    has = os.path.exists(os.path.join(HERE, "gb300_out.bin"))
    open(os.path.join(HERE, "case.toml"), "w").write(
        CASE.format(
            name="cvt_s2f6",
            desc="""N-CVT-LP s2f6 probe (gen.py): the MXINT8 dequant cvt.rn[.relu][.satfinite]
.scaled::n2::ue8m0.bf16x2.s2f6x2 in its four forms, on 1024 threads sampled from the full set
(every pair of 16 edge codes and scales, then fixed random threads). Both front-ends (the SASS
one on kernel.cubin, ptxas 13.1's F2FP...S2_6.UNPACK_B) must equal gb300_out.bin, GB300's
output; gb200_out.bin is GB200's (sm_100a build), equal to it. sweep.json holds the hashes of
GB300's and GB200's outputs of the full set (gen.py --full), equal per form, replayed against
the model by crates/sim/tests/lowp.rs.""",
            ptx="kernel.ptx",
            grid=8,
            n=1024,
            x="in_x.bin",
            y="in_y.bin",
            nout=1024 * n_ops,
            expect='\nexpect = "gb300_out.bin"' if has else "",
        )
    )


if __name__ == "__main__":
    main()
