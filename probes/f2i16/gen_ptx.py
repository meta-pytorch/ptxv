"""Writes kernel.ptx for probes/f2i16: thread g (8 CTAs x 256) prefetches in[g]
(prefetch.global.L1 / .L2: SASS CCTL.E.PF1 / CCTL.E.PF2 or CCTL.PF), loads x = in[g] (f32) and
stores, for j = 0..15 (rounding r = j % 4 in rni, rzi, rmi, rpi; j / 4 = s16, u16, s16.ftz,
u16.ftz): out16[j][g] = cvt.<r>[.ftz].<s16|u16>.f32 x (SASS F2I[.FTZ].{S16,U16}[.TRUNC|.FLOOR|
.CEIL].NTZ) and out32[j][g] = the same value widened by cvt.s32.s16 / cvt.u32.u16 (ptxas may
read the F2I register directly)."""

N = 2048
R = ["rni", "rzi", "rmi", "rpi"]
L = []
e = L.append
e("""// Generated by gen_ptx.py (see there for the output layout).
.version 8.8
.target sm_103a
.address_size 64

.visible .entry f2i16(
    .param .u64 pin, .param .u64 po16, .param .u64 po32
)
.maxntid 256, 1, 1
{
    .reg .b32 %r<40>;
    .reg .b64 %rd<16>;
    .reg .f32 %f<4>;
    .reg .b16 %h<40>;
    mov.u32 %r1, %tid.x;
    mov.u32 %r2, %ctaid.x;
    mad.lo.u32 %r3, %r2, 256, %r1;
    ld.param.u64 %rd1, [pin];
    ld.param.u64 %rd2, [po16];
    ld.param.u64 %rd3, [po32];
    cvta.to.global.u64 %rd1, %rd1;
    cvta.to.global.u64 %rd2, %rd2;
    cvta.to.global.u64 %rd3, %rd3;
    mul.wide.u32 %rd4, %r3, 4;
    mul.wide.u32 %rd5, %r3, 2;
    add.s64 %rd1, %rd1, %rd4;
    add.s64 %rd2, %rd2, %rd5;
    add.s64 %rd3, %rd3, %rd4;
    prefetch.global.L1 [%rd1];
    prefetch.global.L2 [%rd1];
    ld.global.f32 %f1, [%rd1];""")
for j in range(16):
    t = "s16" if j // 4 % 2 == 0 else "u16"
    ftz = ".ftz" if j >= 8 else ""
    e(f"    cvt.{R[j % 4]}{ftz}.{t}.f32 %h{j + 1}, %f1;")
    e(f"    st.global.b16 [%rd2+{j * N * 2}], %h{j + 1};")
    e(f"    cvt.{'s32' if t == 's16' else 'u32'}.{t} %r{j + 10}, %h{j + 1};")
    e(f"    st.global.u32 [%rd3+{j * N * 4}], %r{j + 10};")
e("    ret;\n}")
open("kernel.ptx", "w").write("\n".join(L) + "\n")
