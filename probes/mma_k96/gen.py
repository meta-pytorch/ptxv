"""probes/mma_k96: tcgen05.mma.kind::mxf4nvf4 with K = 96 (instruction descriptor bit 31,
sm_103), scale_vec::4X (block16). Writes kernel.ptx (entries k96_ns: K-major, no swizzle;
k96_sw: K-major, SWIZZLE_128B, 128-byte rows) from kernel.tmpl, and one case directory per
input set. Each entry: M = 128, N = 64, one CTA, two MMAs (K slices 0 and 1; MMA 0 overwrites
D, MMA 1 accumulates), scale factors written to TMEM with tcgen05.st (SFA[t][j] -> lane t,
column 64 + j; SFB[t][j] -> lane t, column 96 + j, j < 16); MMA k reads SFA at column
SFA + sfcol + 8 k, SFB at SFB + sfcol + 8 k (N = 256: SFB + sfcol for both).

Identification sets (exact arithmetic: D reveals which scale byte each 16-element block
used): id_sfa* (A = 1, B row n nonzero only in block n % 6 of slice 0, SFB = 1, every SFA byte
a distinct ue4m3 value by (lane, column, byte)), id_sfb* (the mirror), with scale-factor id 0
or 2. layout_*: random E2M1 codes, all scales 1 (D is an exact sum)."""

import os
import random
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
M, KS = 128, 2  # rows, MMAs


def base(n):
    """idesc: K = 96, M = 128, N = n, ue4m3 scales, A / B E2M1 (1), sf ids 0."""
    return 0x88000480 | (n >> 3) << 17


ONE = 0x38  # ue4m3 1.0
NS = dict(
    rowb=48 * KS,
    adesc=0x0000400800800000,  # LBO 2048 (128 rows x 16 B), SBO 128
    astep=(3 * 2048) >> 4,
)
SW = dict(
    rowb=128,
    adesc=0x4000404000010000,  # SWIZZLE_128B, LBO 16, SBO 1024
    astep=48 >> 4,
)


def bdesc(lay, n):
    if lay is SW:
        return 0x4000404000010000, 48 >> 4
    # No swizzle: LBO = n x 16 B, SBO 128.
    return 0x0000400800000000 | ((n * 16) >> 4) << 16, (3 * n * 16) >> 4


# Entries: name -> (layout, N, TMEM columns, SFA column, SFB column).
ENTRIES = {
    "k96_ns": (NS, 64, 128, 64, 96),
    "k96_sw": (SW, 64, 128, 64, 96),
    "k96_n128": (NS, 128, 256, 128, 160),
    "k96_n256": (NS, 256, 512, 256, 288),
    # Absolute leading-dimension address mode (descriptor bit 52), SWIZZLE_128B: A rows of
    # 256 bytes in global memory land as two 16 KB tiles, R0 = smA and R1 = smA + 16384; MMA 0
    # starts 96 bytes into R0's rows with LBO = R1's address, MMA 1 at R0's row start (same
    # LBO). B as k96_sw.
    "k96_abs": (SW, 64, 128, 64, 96),
}


def kernel():
    t = open(os.path.join(HERE, "kernel.tmpl")).read()
    out = [
        "// probes/mma_k96 (generated by gen.py from kernel.tmpl; do not edit).\n"
        ".version 9.0\n.target sm_103a\n.address_size 64\n"
    ]
    for name, (L, n, tcols, sfa, sfb) in ENTRIES.items():
        d = 2 if L is SW else 3
        z = ", ".join(["%r8"] * d)
        loads = "\n".join(
            f"    cp.async.bulk.tensor.{d}d.shared::cluster.global.mbarrier::complete_tx::bytes"
            f" [{s}], [{tm}, {{{z}}}], [%r3];"
            for s, tm in [("%r6", "%rd1"), ("%r7", "%rd3")]
        )
        bd, bstep = bdesc(L, n)
        ab, bb = M * L["rowb"], n * L["rowb"]
        aextra, adesc, astep = "", L["adesc"], L["astep"]
        if name == "k96_abs":
            ab = 2 * M * 128
            loads = "\n".join(
                "    cp.async.bulk.tensor.2d.shared::cluster.global.mbarrier::complete_tx::bytes"
                f" [{s}], [{tm}, {{{x}, %r8}}], [%r3];"
                for s, tm, x in [
                    ("%r6", "%rd1", "%r8"),
                    ("%r29", "%rd1", "%r28"),
                    ("%r7", "%rd3", "%r8"),
                ]
            )
            loads = (
                "    mov.u32         %r28, 128;\n    add.u32         %r29, %r6, 16384;\n"
                + loads
            )
            adesc |= 1 << 52
            aextra = (
                "    // LBO = R1's absolute address (>> 4); start 96 bytes into the row.\n"
                "    add.u32         %r30, %r6, 16384;\n    shr.u32         %r30, %r30, 4;\n"
                "    cvt.u64.u32     %rd24, %r30;\n    shl.b64         %rd24, %rd24, 16;\n"
                "    and.b64         %rd5, %rd5, 0xffffffffc000ffff;\n"
                "    or.b64          %rd5, %rd5, %rd24;\n    add.u64         %rd5, %rd5, 6;\n"
            )
            astep = -6
        s = (
            t.replace("@NAME@", name)
            .replace("@ABYTES@", str(max(ab, 1024)))
            .replace("@BBYTES@", str(max(bb, 1024)))
            .replace("@TX@", str(ab + bb))
            .replace("@LOADS@", loads)
            .replace("@ADESC@", "0x%016x" % adesc)
            .replace("@AEXTRA@", aextra)
            .replace("@BDESC@", "0x%016x" % bd)
            .replace("@ASTEP@", str(astep))
            .replace("@BSTEP@", str(bstep))
            .replace("@TCOLS@", str(tcols))
            .replace("@SFA@", str(sfa))
            .replace("@SFB@", str(sfb))
            .replace("@SFA8@", str(sfa + 8))
            # N = 256: SFB spans 16 columns (two groups of 8); MMA 1 reuses MMA 0's.
            .replace("@SFB8@", str(sfb + (8 if n < 256 else 0)))
            .replace("@ROWB@", str(4 * n))
            .replace("@NCH@", str(n // 16))
        )
        out.append(s)
    open(os.path.join(HERE, "kernel.ptx"), "w").write("\n".join(out))


def calib_kernel():
    """calib/kernel.ptx: entry mma_nvf4_k96, four K = 96 MMAs (the probes/mma_bs shape for
    `ptxv calib-mma`): A / B K-major without swizzle, 192 bytes per row (12 chunks), MMA k at
    chunk 3 k; SFA[t][j] -> lane t, column 64 + j, SFB[t][j] -> column 96 + j (j < 32); MMA k
    reads SFA at 64 + 8 k, SFB at 96 + 8 k."""
    t = open(os.path.join(HERE, "kernel.tmpl")).read()
    rep = {
        "@NAME@": "mma_nvf4_k96",
        "@ABYTES@": "24576",
        "@BBYTES@": "12288",
        "@TX@": "36864",
        "@TCOLS@": "128",
        "@ADESC@": "0x0000400800800000",
        "@BDESC@": "0x0000400800400000",
        "@ROWB@": "256",
        "@NCH@": "4",
        "@AEXTRA@": "",
    }
    for k, v in rep.items():
        t = t.replace(k, v)
    t = t.replace(
        "@LOADS@",
        "\n".join(
            "    cp.async.bulk.tensor.3d.shared::cluster.global.mbarrier::complete_tx::bytes"
            f" [{s}], [{tm}, {{%r8, %r8, %r8}}], [%r3];"
            for s, tm in [("%r6", "%rd1"), ("%r7", "%rd3")]
        ),
    )

    def sf(buf, col):
        s = (
            f"    ld.param.u64    %rd20, [{buf}];\n    cvta.to.global.u64 %rd20, %rd20;\n"
            "    mul.wide.u32    %rd21, %r0, 128;\n    add.u64         %rd22, %rd20, %rd21;\n"
        )
        regs = [f"%r{50 + i}" for i in range(16)]
        for half in range(2):
            for q in range(4):
                s += (
                    f"    ld.global.v4.b32 {{{', '.join(regs[4 * q : 4 * q + 4])}}},"
                    f" [%rd22+{64 * half + 16 * q}];\n"
                )
            s += f"    add.u32         %r47, %r42, {col + 16 * half};\n"
            s += f"    tcgen05.st.sync.aligned.32x32b.x16.b32 [%r47], {{{', '.join(regs)}}};\n"
        return s

    i = t.index("    ld.param.u64    %rd20, [sfa];")
    j = t.index("    tcgen05.wait::st.sync.aligned;")
    t = t[:i] + sf("sfa", 64) + sf("sfb", 96) + t[j:]
    i = t.index("    add.u32         %r48, %r44, @SFA@;")
    j = t.index("    tcgen05.commit.cta_group::1")
    mm = ""
    for k in range(4):
        if k == 0:
            mm += "    mov.u64         %rd8, %rd5;\n    mov.u64         %rd9, %rd7;\n"
        else:
            mm += f"    add.u64         %rd8, %rd5, {384 * k};\n    add.u64         %rd9, %rd7, {192 * k};\n"
        mm += f"    add.u32         %r48, %r44, {64 + 8 * k};\n    add.u32         %r49, %r44, {96 + 8 * k};\n"
        mm += (
            "    tcgen05.mma.cta_group::1.kind::mxf4nvf4.block_scale.block16 [%r5], %rd8, %rd9, "
            f"{'%r40' if k == 0 else '%r11'}, [%r48], [%r49], {'%p3' if k == 0 else '%p4'};\n"
        )
    t = t[:i] + mm + t[j:]
    hdr = (
        "// probes/mma_k96/calib: `ptxv calib-mma probes/mma_k96/calib` (generated by ../gen.py;\n"
        "// do not edit). D[128x64] = sum of four kind::mxf4nvf4 block16 K = 96 MMAs (idesc0 for\n"
        "// the first, idesc for the rest), A / B K-major without swizzle, 192 bytes per row; MMA k\n"
        "// reads its 48-byte K slice at chunk 3 k, SFA at column 64 + 8 k, SFB at 96 + 8 k.\n"
        ".version 9.0\n.target sm_103a\n.address_size 64\n\n"
    )
    open(os.path.join(HERE, "calib", "kernel.ptx"), "w").write(hdr + t)


def pack(codes, rows, rowb):
    """codes[r][k] (K = 96 KS) -> rows x rowb bytes, two E2M1 per byte, low nibble first."""
    out = bytearray(rows * rowb)
    for r in range(rows):
        for k in range(96 * KS):
            out[r * rowb + k // 2] |= (codes[r][k] & 0xF) << (4 * (k % 2))
    return bytes(out)


def sfw(f):
    """SF words [128][16] u32: byte q of lane t, column j = f(t, j, q)."""
    w = []
    for t in range(128):
        for j in range(16):
            w.append(sum(f(t, j, q) << (8 * q) for q in range(4)))
    return struct.pack("<2048I", *w)


UE = [c for c in range(0x08, 0x7F)]  # 119 normal ue4m3 codes


def ident(t, j, q):
    return UE[(t * 64 + j * 4 + q) % len(UE)]


def write_set(name, entry, a, b, sa, sb, idesc0, idesc, sfcol=0):
    L, N = ENTRIES[entry][0], ENTRIES[entry][1]
    d = os.path.join(HERE, name)
    os.makedirs(d, exist_ok=True)
    arow = 256 if entry == "k96_abs" else L["rowb"]
    open(os.path.join(d, "A.bin"), "wb").write(
        bytes(a) if entry == "k96_abs" else pack(a, M, arow)
    )
    open(os.path.join(d, "B.bin"), "wb").write(pack(b, N, L["rowb"]))
    open(os.path.join(d, "SFA.bin"), "wb").write(sfw(sa))
    open(os.path.join(d, "SFB.bin"), "wb").write(sfw(sb))
    rowb = L["rowb"]
    if L is NS:
        nch = rowb // 16
        tm = lambda buf, rows: (
            f'[[params]]\nkind = "tensormap"\nbuffer = "{buf}"\nbox = [16, {rows}, {nch}]\n'
            f"dims = [16, {rows}, {nch}]\nstrides = [{rowb}, 16]\n"
        )
    else:
        tm = lambda buf, rows: (
            f'[[params]]\nkind = "tensormap"\nbuffer = "{buf}"\nbox = [128, {rows}]\n'
            f"dims = [{arow if buf == 'A' else 128}, {rows}]\n"
            f'strides = [{arow if buf == "A" else 128}]\nswizzle = "128B"\n'
        )
    toml = f'''name = "mma_k96_{name}"
description = "probes/mma_k96 input set {name} (gen.py): kind::mxf4nvf4 block16, K = 96."
ptx = "../kernel.ptx"
entry = "{entry}"
grid = [1, 1, 1]
block = [128, 1, 1]
outputs = ["D"]

[[buffers]]
name = "A"
dtype = "u8"
shape = [{M}, {arow}]
init = "file"
file = "A.bin"

[[buffers]]
name = "B"
dtype = "u8"
shape = [{N}, {rowb}]
init = "file"
file = "B.bin"

[[buffers]]
name = "SFA"
dtype = "u32"
shape = [128, 16]
init = "file"
file = "SFA.bin"

[[buffers]]
name = "SFB"
dtype = "u32"
shape = [128, 16]
init = "file"
file = "SFB.bin"

[[buffers]]
name = "D"
dtype = "f32"
shape = [{M}, {N}]
init = "nan"
expect = "expected/D.bin"

{tm("A", M)}
{tm("B", N)}
[[params]]
kind = "ptr"
buffer = "D"

[[params]]
kind = "u32"
value = {idesc}

[[params]]
kind = "u32"
value = {idesc0}

[[params]]
kind = "ptr"
buffer = "SFA"

[[params]]
kind = "ptr"
buffer = "SFB"

[[params]]
kind = "u32"
value = {sfcol}

[[variants]]
id = "good"
expect = ["clean"]
'''
    open(os.path.join(d, "case.toml"), "w").write(toml)


def main():
    kernel()
    calib_kernel()
    r = random.Random(96)
    K = 96 * KS
    unit = lambda t, j, q: ONE
    A2, B2 = 0x40000000, 0x20  # scale-factor id 2: A bits 29-30, B bits 4-5
    for e, (L, n, _, _, _) in ENTRIES.items():
        sfx = e[3:]  # "_ns", "_sw", "_n128", "_n256"
        if e == "k96_abs":
            # Random bytes in both A tiles (R0: row bytes 0..127, R1: 128..255), scales 1.
            a = [r.randrange(256) for _ in range(M * 256)]
            b = [[r.randrange(16) for _ in range(K)] for _ in range(n)]
            write_set("abs", e, a, b, unit, unit, base(n), base(n))
            continue
        b0 = base(n)
        one = [[2] * K for _ in range(M)]
        blk_b = [
            [2 if k < 96 and k // 16 == c % 6 else 0 for k in range(K)]
            for c in range(n)
        ]
        blk_a = [
            [2 if k < 96 and k // 16 == m % 6 else 0 for k in range(K)]
            for m in range(M)
        ]
        allb = [[2] * K for _ in range(n)]
        write_set("id_sfa" + sfx, e, one, blk_b, ident, unit, b0, b0)
        write_set("id_sfa_s2" + sfx, e, one, blk_b, ident, unit, b0 | A2, b0)
        write_set("id_sfb" + sfx, e, blk_a, allb, unit, ident, b0, b0)
        write_set("id_sfb_s2" + sfx, e, blk_a, allb, unit, ident, b0 | B2, b0)
        rc = lambda rows: [[r.randrange(16) for _ in range(K)] for _ in range(rows)]
        write_set("layout" + sfx, e, rc(M), rc(n), unit, unit, b0, b0)


def pair_data():
    """pair/: random E2M1 codes (A, B 256 x 48 bytes) and random ue4m3 scale bytes 0x30..0x47
    per (CTA, lane, word, byte) (SFA 8 words, SFB 16 words per lane)."""
    r = random.Random(103)
    d = os.path.join(HERE, "pair")
    for nm, n in [("A.bin", 256 * 48), ("B.bin", 256 * 48)]:
        open(os.path.join(d, nm), "wb").write(bytes(r.randrange(256) for _ in range(n)))
    for nm, w in [("SFA.bin", 8), ("SFB.bin", 16)]:
        open(os.path.join(d, nm), "wb").write(
            bytes(r.randrange(0x30, 0x48) for _ in range(2 * 128 * w * 4))
        )


if __name__ == "__main__":
    main()
    pair_data()
