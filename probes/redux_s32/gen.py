"""probes/redux_s32: inputs (in.bin: 256 words, signed extremes / wrapping sums / random) and
masks/kernel.ptx (one block per active-lane mask, so the PTX membermask is an immediate)."""

import random

import numpy as np

random.seed(5)
OPS = [
    "add.s32",
    "add.u32",
    "and.b32",
    "or.b32",
    "xor.b32",
    "min.s32",
    "max.s32",
    "min.u32",
    "max.u32",
]
MASKS = [
    0xFFFFFFFF,
    0x00000001,
    0x80000000,
    0x55555555,
    0xFFFF0000,
    0xDEADBEEF,
    0x00010001,
    0x7FFFFFFE,
]

v = [
    0x7FFFFFFF,
    0x80000000,
    0xFFFFFFFF,
    0x00000001,
    0x7FFFFFFF,
    0x7FFFFFFF,
    0x80000001,
    0,
]
v += [random.getrandbits(32) for _ in range(24)]  # warp 0
v += [0x7FFFFFFF] * 32  # warp 1: the sum wraps
v += [0x80000000 + i for i in range(32)]  # warp 2: negative extremes
v += [
    random.choice([0, 1, 0xFFFFFFFF, 0x80000000, 0x7FFFFFFF, random.getrandbits(32)])
    for _ in range(32)
]  # warp 3
v += [random.getrandbits(32) for _ in range(128)]  # atomic increments / mask warps
np.array(v, np.uint32).tofile("in.bin")

# masks/kernel.ptx: warp w (8 warps) runs the reductions with only the lanes of MASKS[w]
# active; out[(w * 32 + lane) * 9 + j] = op j's result, 0 for inactive lanes.
body = []
for w, m in enumerate(MASKS):
    body.append(f"""    setp.eq.u32     %p1, %r20, {w};
    shr.b32         %r21, {m:#010x}, %r1;
    and.b32         %r21, %r21, 1;
    setp.eq.and.u32 %p2, %r21, 1, %p1;
    @!%p2 bra       SKIP{w};""")
    for j, op in enumerate(OPS):
        body.append(f"    redux.sync.{op} %r{30 + j}, %r4, {m:#010x};")
    for j in range(len(OPS)):
        body.append(f"    st.global.u32   [%rd4+{4 * j}], %r{30 + j};")
    body.append(f"SKIP{w}:")
ptx = (
    """// probes/redux_s32/masks (generated by ../gen.py): redux.sync with partial membermasks, each
// executed by exactly the lanes of its mask (SASS REDUX / CREDUX under divergence). Warp w of
// 256 threads uses MASKS[w] (gen.py); lane l loads x = in[32 w + l] and, if active, stores
// out[9 (32 w + l) + j] = redux.sync.<OPS[j]> of x over the active lanes.
.version 8.8
.target sm_103a
.address_size 64

.visible .entry redux_masks(
    .param .u64 pin,
    .param .u64 pout
)
.maxntid 256, 1, 1
{
    .reg .pred  %p<4>;
    .reg .b32   %r<48>;
    .reg .b64   %rd<8>;

    ld.param.u64    %rd1, [pin];
    ld.param.u64    %rd2, [pout];
    cvta.to.global.u64 %rd1, %rd1;
    cvta.to.global.u64 %rd2, %rd2;
    mov.u32         %r3, %tid.x;
    and.b32         %r1, %r3, 31;
    shr.u32         %r20, %r3, 5;
    mul.wide.u32    %rd3, %r3, 4;
    add.s64         %rd3, %rd1, %rd3;
    ld.global.u32   %r4, [%rd3];
    mul.wide.u32    %rd4, %r3, 36;
    add.s64         %rd4, %rd2, %rd4;
"""
    + "\n".join(body)
    + "\n    ret;\n}\n"
)
open("masks/kernel.ptx", "w").write(ptx)
