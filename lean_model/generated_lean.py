"""Publish generated Lean with a fixed license comment and unchanged tool bytes."""

import hashlib
import json
from pathlib import Path

PREAMBLE = b"""/-
Copyright (c) Meta Platforms, Inc. and affiliates.

This source code is licensed under the BSD-style license found in the
LICENSE file in the root directory of this source tree.
-/

"""
NAMES = ("Funs.lean", "Types.lean")
POLICY = {
    "version": 1,
    "transformation": "prepend-license-comment",
    "preamble_sha256": hashlib.sha256(PREAMBLE).hexdigest(),
}


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def publish(generated: Path, evidence: Path) -> dict:
    if sorted(path.name for path in generated.iterdir()) != list(NAMES):
        raise ValueError("Expected exactly Funs.lean and Types.lean from Aeneas")
    evidence.mkdir(parents=True, exist_ok=False)
    files = {}
    for name in NAMES:
        path = generated / name
        raw = path.read_bytes()
        if not raw.startswith(b"-- THIS FILE WAS AUTOMATICALLY GENERATED BY AENEAS"):
            raise ValueError(f"Expected raw Aeneas output: {path}")
        (evidence / name).write_bytes(raw)
        published = PREAMBLE + raw
        path.write_bytes(published)
        files[name] = {"raw_sha256": digest(raw), "published_sha256": digest(published)}
    record = {"policy": POLICY, "files": files}
    (evidence / "export.json").write_text(
        json.dumps(record, indent=2, sort_keys=True) + "\n"
    )
    verify(generated, record, evidence)
    return record


def verify(generated: Path, record: dict, evidence: Path | None = None) -> None:
    if record["policy"] != POLICY or set(record["files"]) != set(NAMES):
        raise ValueError("Generated Lean export policy or inventory changed")
    for name in NAMES:
        published = (generated / name).read_bytes()
        if not published.startswith(PREAMBLE):
            raise ValueError(f"Generated Lean license preamble changed: {name}")
        raw = published[len(PREAMBLE) :]
        if not raw.startswith(b"-- THIS FILE WAS AUTOMATICALLY GENERATED BY AENEAS"):
            raise ValueError(f"Generated Lean body is not raw Aeneas output: {name}")
        expected = {"raw_sha256": digest(raw), "published_sha256": digest(published)}
        if record["files"][name] != expected:
            raise ValueError(f"Generated Lean export fingerprints changed: {name}")
        if evidence is not None and (evidence / name).read_bytes() != raw:
            raise ValueError(
                f"Generated Lean body differs from raw Aeneas output: {name}"
            )
